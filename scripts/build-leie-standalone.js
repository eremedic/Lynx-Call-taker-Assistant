// Builds public/leie/lynx-leie-screening.html: the LEIE screening page as one
// self-contained file (styles, scripts and logo inlined) that can be saved to
// a computer and opened by double-clicking it, with no web server.
// Run with: npm run build:leie
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'public', 'leie');
export const OUTPUT = path.join(dir, 'lynx-leie-screening.html');

export function buildStandalone() {
  const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
  const logo = 'data:image/png;base64,' + fs.readFileSync(path.join(dir, 'lynx-ems-logo.png')).toString('base64');
  const inlineScript = (f) => `<script>\n${read(f).replace(/<\/script/gi, '<\\/script')}</script>`;
  let html = read('index.html')
    .replace('<link rel="stylesheet" href="leie.css">', () => `<style>\n${read('leie.css')}</style>`)
    .replace(/<script src="([\w.-]+\.js)"><\/script>/g, (_, f) => inlineScript(f));
  html = html.replaceAll('lynx-ems-logo.png', logo);
  return '<!-- Generated by scripts/build-leie-standalone.js from public/leie/. Do not edit by hand. -->\n' + html;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUTPUT, buildStandalone());
  console.log('Wrote', path.relative(process.cwd(), OUTPUT));
}
